      // 7. Instant Hover / Touch Link Prefetching for Multi-Page Navigation
      const prefetchedUrls = new Set();
      function initSmartLinkPrefetch() {
        const triggerPrefetch = (e) => {
          const a = e.target && e.target.closest ? e.target.closest('a[href]') : null;
          if (!a) return;
          const href = (a.getAttribute('href') || '').trim();
          if (!href || href.startsWith('#') || href.startsWith('mailto:') || href.startsWith('tel:') || href.startsWith('http') || href.endsWith('.pdf')) return;
          if (prefetchedUrls.has(href)) return;
          prefetchedUrls.add(href);
          const link = document.createElement('link');
          link.rel = 'prefetch';
          link.href = href;
          document.head.appendChild(link);
        };
        document.addEventListener('mouseover', triggerPrefetch, { passive: true });
        document.addEventListener('touchstart', triggerPrefetch, { passive: true });
      }

